/**
 * 満月齢 month・パーセンタイルの位置 pi（0〜6）の基準値を返す。
 * 公表値の代表点に当たる月齢はその値を、当たらない月齢は前後の代表点から直線で補間した値を返す。
 */
export function growthValue2010(
  classes: GrowthClass2010[], sex: '1' | '2', month: number, pi: number,
): { value: number; interpolated: boolean } {
  const pick = (c: GrowthClass2010) => (sex === '1' ? c.male[pi] : c.female[pi]);
  for (let i = 0; i < classes.length; i++) {
    const c = classes[i];
    if (c.index === month) return { value: pick(c), interpolated: false };
    if (c.index > month) {
      if (i === 0) return { value: pick(c), interpolated: true };
      const prev = classes[i - 1];
      const t = (month - prev.index) / (c.index - prev.index);
      return { value: pick(prev) + (pick(c) - pick(prev)) * t, interpolated: true };
    }
  }
  return { value: pick(classes[classes.length - 1]), interpolated: true };
}
